"""Final metadata and MathJax hygiene pass for the repaired math batch."""

from __future__ import annotations

import json
import re
import shutil
import unicodedata
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "data" / "l12" / "toan"


def ascii_text(value: str) -> str:
    return "".join(c for c in unicodedata.normalize("NFD", value.lower()) if unicodedata.category(c) != "Mn")


def infer_type(payload: dict, filename: str) -> str:
    text = ascii_text(f"{filename} {payload.get('title', '')}").replace("_", "-")
    if re.search(r"hoc-sinh-gioi|chon-hsg|\bhsg\b|olympic", text):
        return "hsg"
    if re.search(r"tot-nghiep|thi-thu-(?:tn|thpt)|on-thi-(?:tn|thpt)", text):
        return "totnghiep"
    if re.search(r"giua-(?:hoc-)?(?:ky|ki)-?1|giua-hk-?1", text):
        return "giuaki1"
    if re.search(r"cuoi-(?:hoc-)?(?:ky|ki)-?1|(?:thi-)?hk-?1", text):
        return "cuoiki1"
    if re.search(r"giua-(?:hoc-)?(?:ky|ki)-?2|giua-hk-?2", text):
        return "giuaki2"
    if re.search(r"cuoi-(?:hoc-)?(?:ky|ki)-?2|(?:thi-)?hk-?2", text):
        return "cuoiki2"
    return "khaosat"


def fix_currency_dollars(value: object) -> object:
    if not isinstance(value, str):
        return value
    # Literal currency markers from PDF extraction must not become MathJax
    # delimiters. Existing balanced math fragments generated by the repair pass
    # contain no whitespace immediately before the closing delimiter.
    value = re.sub(r"\(\s*\$\s*\)", "(USD)", value)
    value = re.sub(r"(?<=\d)\s+\$(?![^$]*\$)", " USD", value)
    value = re.sub(r"(?<=m)\$(?=[,.;])", "", value)
    if len(re.findall(r"(?<!\\)\$", value)) % 2:
        # An unmatched dollar is always malformed in HTML/MathJax data. Keep
        # the visible character as a currency label instead of hiding prose.
        value = value.replace("$", " USD ")
    return value


def main() -> None:
    moved = fixed = collisions = 0
    for path in sorted(BASE.rglob("*.json")):
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        if not payload.get("repairNote"):
            continue
        if str(payload.get("sourceId", "")).startswith("garanmath:"):
            slug = payload["sourceId"].split(":", 1)[1]
            payload["sourceUrl"] = f"https://toanmath.com/toanmath-pdf/{slug}.pdf"
        elif payload.get("source") == "tailieuonthi.org" and payload.get("id", "").startswith("tlot-toan-hsa-"):
            slug = payload["id"].removeprefix("tlot-toan-hsa-")
            payload["sourceUrl"] = f"https://tailieuonthi.org/{slug}/"
        for question in payload.get("questions", []):
            question["content"] = fix_currency_dollars(question.get("content", ""))
            if "options" in question:
                question["options"] = [fix_currency_dollars(v) for v in question["options"]]
            if "explanation" in question:
                question["explanation"] = fix_currency_dollars(question["explanation"])
        wanted = payload.get("examType") if payload.get("source") == "tailieuonthi.org" else infer_type(payload, path.name)
        payload["examType"] = wanted
        serialized = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
        destination = BASE / wanted / path.name
        destination.parent.mkdir(parents=True, exist_ok=True)
        if destination.resolve() != path.resolve():
            if destination.exists():
                collisions += 1
                path.write_text(serialized, encoding="utf-8")
            else:
                destination.write_text(serialized, encoding="utf-8")
                path.unlink()
                moved += 1
        else:
            path.write_text(serialized, encoding="utf-8")
        fixed += 1
    print(json.dumps({"files": fixed, "moved": moved, "collisions": collisions}, ensure_ascii=False))


if __name__ == "__main__":
    main()
